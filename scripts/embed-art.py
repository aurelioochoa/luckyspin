#!/usr/bin/env python3
"""Embed generated artwork so installed binaries need no asset folder."""
import sys
from pathlib import Path

source, target = map(Path, sys.argv[1:])
data = source.read_bytes()
with target.open("w") as output:
    output.write("// Generated by scripts/embed-art.py. Do not edit.\n#pragma once\nnamespace assets {\n")
    output.write("const unsigned char CASINO_PNG[] = {\n")
    for start in range(0, len(data), 24):
        output.write(",".join(str(byte) for byte in data[start:start + 24]) + ",\n")
    output.write("};\n}\n")
